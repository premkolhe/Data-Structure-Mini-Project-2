"""Generate and display a perfect maze using randomized depth-first search."""

from __future__ import annotations

import argparse
import random
from dataclasses import dataclass


# A cell keeps track of the four walls that still enclose it.
NORTH, EAST, SOUTH, WEST = 0, 1, 2, 3
DIRECTIONS = (
    (-1, 0, NORTH, SOUTH),
    (0, 1, EAST, WEST),
    (1, 0, SOUTH, NORTH),
    (0, -1, WEST, EAST),
)


@dataclass
class Cell:
    walls: list[bool]

    @classmethod
    def enclosed(cls) -> "Cell":
        return cls(walls=[True, True, True, True])


class Maze:
    """A rectangular maze generated by the iterative DFS backtracking method."""

    def __init__(self, rows: int, cols: int, seed: int | None = None) -> None:
        if not 2 <= rows <= 40 or not 2 <= cols <= 40:
            raise ValueError("Rows and columns must both be between 2 and 40.")

        self.rows = rows
        self.cols = cols
        self.random = random.Random(seed)
        self.cells = [[Cell.enclosed() for _ in range(cols)] for _ in range(rows)]

    def generate(self) -> None:
        """Carve passages through all cells using a stack instead of recursion."""
        visited = [[False] * self.cols for _ in range(self.rows)]
        stack = [(0, 0)]
        visited[0][0] = True

        while stack:
            row, col = stack[-1]
            neighbors = []

            for row_step, col_step, wall, opposite_wall in DIRECTIONS:
                next_row = row + row_step
                next_col = col + col_step
                if (0 <= next_row < self.rows and
                        0 <= next_col < self.cols and
                        not visited[next_row][next_col]):
                    neighbors.append((next_row, next_col, wall, opposite_wall))

            if not neighbors:
                stack.pop()
                continue

            next_row, next_col, wall, opposite_wall = self.random.choice(neighbors)
            self.cells[row][col].walls[wall] = False
            self.cells[next_row][next_col].walls[opposite_wall] = False
            visited[next_row][next_col] = True
            stack.append((next_row, next_col))

    def render(self) -> str:
        """Return an ASCII view with an entrance at start and an exit at finish."""
        lines = []

        # Open the north wall of the first cell to mark the entrance.
        top = "+"
        for col in range(self.cols):
            top += "   +" if col == 0 else ("---+" if self.cells[0][col].walls[NORTH] else "   +")
        lines.append(top)

        for row in range(self.rows):
            middle = "|"
            for col in range(self.cols):
                east_wall = self.cells[row][col].walls[EAST]
                middle += "   " + ("|" if east_wall else " ")
            lines.append(middle)

            bottom = "+"
            for col in range(self.cols):
                # Leave an opening at the bottom of the final cell as the exit.
                if row == self.rows - 1 and col == self.cols - 1:
                    bottom += "   +"
                else:
                    bottom += "---+" if self.cells[row][col].walls[SOUTH] else "   +"
            lines.append(bottom)

        return "\n".join(lines)


def read_dimension(label: str, default: int) -> int:
    while True:
        answer = input(f"Number of {label} (2-40) [{default}]: ").strip()
        if not answer:
            return default
        try:
            value = int(answer)
            if 2 <= value <= 40:
                return value
        except ValueError:
            pass
        print("Enter a whole number from 2 to 40.")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate a maze with randomized DFS.")
    parser.add_argument("--seed", type=int, help="Optional random seed for a repeatable maze.")
    args = parser.parse_args()

    print("MAZE GENERATION USING DEPTH-FIRST SEARCH")
    print("Enter maze dimensions. Press Enter to use the defaults.\n")
    rows = read_dimension("rows", 10)
    cols = read_dimension("columns", 20)

    maze = Maze(rows, cols, seed=args.seed)
    maze.generate()
    print(f"\nGenerated a {rows} x {cols} maze using randomized DFS.")
    print("Entrance: top-left | Exit: bottom-right\n")
    print(maze.render())


if __name__ == "__main__":
    main()
